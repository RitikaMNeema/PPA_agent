"""Design configuration: load config.json, read the SDC, generate the top wrapper.

The top wrapper is where *tuning knobs* (core parameters) are applied, so the
same RTL source can be explored across configurations without editing it.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from env import ROOT, DESIGN


@dataclass
class DesignConfig:
    design: str
    top: str
    core: str
    sdc: Path
    rtl: list[Path]
    params: dict
    synth: dict = field(default_factory=dict)

    @property
    def clock_period_ns(self) -> float:
        m = re.search(r"set\s+clk_period\s+([\d.]+)", self.sdc.read_text())
        if not m:
            m = re.search(r"create_clock.*-period\s+([\d.]+)", self.sdc.read_text())
        return float(m.group(1))

    @property
    def clock_uncertainty_ns(self) -> float:
        m = re.search(r"set_clock_uncertainty\s+([\d.]+)", self.sdc.read_text())
        return float(m.group(1)) if m else 0.0

    def to_json(self) -> dict:
        return {"design": self.design, "top": self.top, "core": self.core,
                "sdc": str(self.sdc.relative_to(ROOT)).replace("\\", "/"),
                "rtl": [str(p.relative_to(ROOT)).replace("\\", "/") for p in self.rtl],
                "params": self.params, "synth": self.synth}


def load_config(path: Path | None = None) -> DesignConfig:
    path = path or DESIGN / "config.json"
    d = json.loads(Path(path).read_text())
    return DesignConfig(d["design"], d["top"], d["core"], ROOT / d["sdc"],
                        [ROOT / p for p in d["rtl"]], d["params"], d.get("synth", {}))


def write_top(cfg: DesignConfig, out: Path) -> Path:
    params = ",\n".join(f"\t\t.{k}({v})" for k, v in cfg.params.items())
    out.write_text(f"""// AUTO-GENERATED by flow/design.py from config.json -- do not edit.
module {cfg.top} (
	input clk, resetn,
	output trap,
	output mem_valid, mem_instr,
	input  mem_ready,
	output [31:0] mem_addr, mem_wdata,
	output [ 3:0] mem_wstrb,
	input  [31:0] mem_rdata,
	input  [31:0] irq,
	output [31:0] eoi
);
	{cfg.core} #(
{params}
	) core (
		.clk(clk), .resetn(resetn), .trap(trap),
		.mem_valid(mem_valid), .mem_instr(mem_instr), .mem_ready(mem_ready),
		.mem_addr(mem_addr), .mem_wdata(mem_wdata), .mem_wstrb(mem_wstrb), .mem_rdata(mem_rdata),
		.mem_la_read(), .mem_la_write(), .mem_la_addr(), .mem_la_wdata(), .mem_la_wstrb(),
		.pcpi_valid(), .pcpi_insn(), .pcpi_rs1(), .pcpi_rs2(),
		.pcpi_wr(1'b0), .pcpi_rd(32'b0), .pcpi_wait(1'b0), .pcpi_ready(1'b0),
		.irq(irq), .eoi(eoi),
		.trace_valid(), .trace_data()
	);
endmodule
""")
    return out
